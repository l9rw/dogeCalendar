export type HolidayStatus = 'rest' | 'workday';

export interface HolidayOverride {
  name: string;
  status: HolidayStatus;
}

type HolidayGroup = [name: string, rest: string, workday?: string];

const group = ([name, rest, workday = '']: HolidayGroup): [string, HolidayOverride][] => [
  ...rest.split(',').filter(Boolean).map<[string, HolidayOverride]>((date) => [date, { name, status: 'rest' }]),
  ...workday.split(',').filter(Boolean).map<[string, HolidayOverride]>((date) => [date, { name, status: 'workday' }]),
];

const year = (...groups: HolidayGroup[]): Record<string, HolidayOverride> =>
  Object.fromEntries(groups.flatMap(group));

